    public void useJDialog (Table table, boolean...resizable) {
        dialog = new MyJDialog();
        dialog.setPreferredSize(this.getPreferredSize());
        dialog.setMinimumSize(this.getMinimumSize());
        dialog.add(northPanel, BorderLayout.NORTH);
        dialog.add(scrollPaneContainer, BorderLayout.CENTER);
        dialog.add(southPanel, BorderLayout.SOUTH);
        dialog.setLocation(getLocation());
        dialog.setModal(true);
        dialog.setTitle(getTitle());
        boolean isResizable = (resizable.length != 0);
        dialog.setResizable(isResizable);
        dialog.addWindowListener(new WindowAdapter () {            
            @Override
            public void windowClosing (WindowEvent e) {
                if (table instanceof SavedClassesTable) {
                    SavedClassesTable table1 = (SavedClassesTable) table;
                    table1.endProgress();
                }
            }            
        });
        
        SwingWorker worker = new SwingWorker<Object, Object> () {
            @Override
            protected Object doInBackground() throws Exception {
                dialog.setVisible(true);
                return null;
            }
        };        
        worker.execute();
    }

