    private void viewDashboardActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_viewDashboardActionPerformed
        // TODO add your handling code here:
        
        if (!FrontEndUtility.isTeacherLoggedIn()) {
            FrontEndUtility.showMsgJOptionPane("To access this functionality you need to log in or sign in\nGo to file > setings or press 'Ctrl+Alt+S' ", "Informational message", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        
        setShowingDashboardPanel(true);
        setShowingTree(false);
        setShowingClassPanel(false);
        
        if (dashboard == null)
            setDashboard(new MainForm(connectionLabel));

        remove_addCenterComponent((JComponent) getCenterComponent(), dashboard);
        
        viewDashboard.setEnabled(false);
    }//GEN-LAST:event_viewDashboardActionPerformed

