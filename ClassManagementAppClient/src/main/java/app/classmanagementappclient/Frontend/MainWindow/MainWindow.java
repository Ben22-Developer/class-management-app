    private void remove_addCenterComponent (JComponent toRemoveComponent, JComponent toAddComponent) {
        
        removeComponent(toRemoveComponent);
        addComponentToCenter(toAddComponent);
    }
    
    private Component getCenterComponent () {
        BorderLayout layout = (BorderLayout) getContentPane().getLayout();
        return layout.getLayoutComponent(BorderLayout.CENTER);
    } 
    
    private void removeComponent (JComponent component) 
    {
        if (component == null)
            return;
        remove(component);
    }
    
    private void addComponentToCenter (JComponent component) {
        SwingUtilities.invokeLater(() -> {
            getContentPane().add(component, BorderLayout.CENTER);
            FrontEndUtility.refresh(this);
        });
    }
    
