    private void initListeners () {
        
        getContentPane().addContainerListener(new ContainerAdapter () {
            
            @Override
            public void componentRemoved(ContainerEvent e) {

                JComponent component = (JComponent) e.getChild();

                SwingUtilities.invokeLater(() -> {

                    if (component.equals(splitPane))
                        treeDisplayMenuItem.setEnabled(true);

                    else if (component.equals(dashboard))
                        viewDashboard.setEnabled(true);

                });
            }
        });
    }
    
