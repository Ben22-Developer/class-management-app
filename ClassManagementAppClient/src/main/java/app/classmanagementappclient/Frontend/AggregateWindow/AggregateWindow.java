    public JTable getReportStructureTable () {
        
        JPanel topPanel = (JPanel) splitPane.getTopComponent();
        
        for (Component component : topPanel.getComponents()) {
            if (component instanceof JPanel panel) {
                BorderLayout layout = (BorderLayout) panel.getLayout();
                JScrollPane pane = (JScrollPane) layout.getLayoutComponent(BorderLayout.CENTER);
                if (pane == null)
                    break;
                return (JTable) pane.getViewport().getView();
            }
        }  
        return null;
    } 
    
    public JTable getTermAssessmentsTable () {
        
        JPanel topPanel = (JPanel) splitPane.getBottomComponent();
        
        for (Component component : topPanel.getComponents())
            if (component instanceof JScrollPane pane)
                return (JTable) pane.getViewport().getView();
        
        return null;
    }

    
    
    @Override
    public String setDetails(ConcurrentHashMap<Integer, Integer> termNumsToTerm, TableDisplay tableDisplay,  TermsDialog dialog) {
        
        String msg = dialog.setClassLessonsTable(termNumsToTerm);
        tableDisplay.getDialog().dispose();
        
        // set attendanceClassTermNums when sure that there's no problem
        if (msg.isBlank()) 
            setAttendanceClassTermNums(Collections.list(termNumsToTerm.keys()));  
        
        return msg;
    }

    @Override
    public void setTerm(Iterator<Integer> iterator) {
        
        List<Integer> assessmentNums = CommonDSManipulation.transformIteratorToList(iterator);
        setAssessmentClassTermNums(assessmentNums);        
    }
