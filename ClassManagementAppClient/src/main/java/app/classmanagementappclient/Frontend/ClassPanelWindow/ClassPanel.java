    public void setTabbedPaneScrollEvent (JTabbedPane tabbedPane) {
      tabbedPane.addMouseWheelListener((l) -> {
          
          int selected = tabbedPane.getSelectedIndex();
          selected += l.getWheelRotation();
          
          if (selected >= 0 && selected < tabbedPane.getTabCount())
              tabbedPane.setSelectedIndex(selected);
      });
    }
    
    public void setSouthPanelChangePaneListener (JTabbedPane tabbedPane, JPanel panel) {
        
      tabbedPane.addMouseWheelListener((l) -> {
          processEvent(tabbedPane, panel);
      }); 
      
      tabbedPane.addMouseListener(new MouseAdapter() {
          @Override
          public void mouseReleased(MouseEvent e) {
              processEvent(tabbedPane, panel);
          }
          
      });       
    }
    
    private void processEvent (JTabbedPane tabbedPane, JPanel panel) {
               
        if (prevAccessedPane == tabbedPane.getSelectedIndex())       
            return;
        
        if (prevAccessedPane != -1)
            southPanelRemoval(tabbedPane);        
        
        prevAccessedPane = tabbedPane.getSelectedIndex();

        JPanel panel1 = (JPanel) tabbedPane.getSelectedComponent();
        panel1.add(panel, BorderLayout.SOUTH);
    }
    
    private void southPanelRemoval (JTabbedPane tabbedPane) {
        JPanel panel = (JPanel) tabbedPane.getComponentAt(prevAccessedPane);
        BorderLayout layout = (BorderLayout) panel.getLayout();
        JComponent component = (JComponent) layout.getLayoutComponent(BorderLayout.SOUTH);   
        layout.removeLayoutComponent(component);
    }
    
