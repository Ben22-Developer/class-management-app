    private void setPopUpMenu () {
        
        // if u attempt to add another JMenuItem  review the method addMenuItemsToPopupMenu, in the for loop the '%' that is there
        JMenuItem[] items = { new JMenuItem("Show Title" ) ,  new JMenuItem ("Hide Title"),  new JMenuItem("Show Settings"),  new JMenuItem("Hide Settings") };
        
        showTitlePopUpEvent(items[0]);
        hideTitlePopUpEvent(items[1]);
        showSettingPopUpEvent(items[2]);
        hideSettingPopUpEvent(items[3]);
        addMenuItemsToPopupMenu(items);
    }
    
    
