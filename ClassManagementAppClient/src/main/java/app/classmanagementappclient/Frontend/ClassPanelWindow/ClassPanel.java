    private void addMenuItemsToPopupMenu (JMenuItem[] items) {
        for (int i = 0; i < items.length; i++) {
            
            if (i != 0 && i % 2 == 0) {
                popupMenu.addSeparator();
            }
            
            FrontEndUtility.setJComponentDefaultFont(items[i]);
            popupMenu.add(items[i]);
        }       
    }
    
