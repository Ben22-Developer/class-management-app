    private void itemEventHandler (ItemEvent evt, JTextField textField)
    {
        if (windowLoading)
            return;
        
        String valueStr = String.valueOf(evt.getItem());
        
        if (evt.getStateChange() == ItemEvent.SELECTED)
            textField.setText(valueStr);
    }
    
    public void setJDialog () 
    {
        MyJDialog dialog = new MyJDialog();
        
        SwingWorker worker = new SwingWorker<Object, Object> () {
            @Override
            protected Object doInBackground() throws Exception 
            {
                dialog.setPreferredSize(getPreferredSize());
                dialog.setMinimumSize(getMinimumSize());
                dialog.setResizable(isResizable());
                dialog.add(buttonsPanel, BorderLayout.NORTH);
                dialog.add(inputPanel, BorderLayout.CENTER);
                dialog.setLocation(getLocation());
                dialog.setTitle(getTitle());
                dialog.setDefaultCloseOperation(JDialog.DISPOSE_ON_CLOSE);
                dialog.setModal(true);
                return null;
            }
            
            @Override
            public void done () {
                dialog.setVisible(true);
            }
        };
        worker.execute();
    }
    
