    public Teacher getTeacher (JTextField nameField, JPasswordField passwordField, JTextField phoneNbrField, JTextField emailTextField) 
    {
        String name = nameField.getText();
        String pin =  getStringPin(passwordField);
        String phoneNumber = phoneNbrField.getText();  
        String email = emailTextField.getText(); 
        return new Teacher(name, pin, phoneNumber, email);
    }
    
    private String getStringPin (JPasswordField passwordField) {
        StringBuilder sb = new StringBuilder();
        for (char c : passwordField.getPassword()) {
            sb.append(c);
        }
        return sb.toString();
    }
    
    public void runSwingUtility (Runnable run) 
    {
        destroyExecutorService();
        es = Executors.newFixedThreadPool(1);
        SwingUtilities.invokeLater(() -> {
           es.submit(run);
           es.shutdown();
       });     
    }
    
    private void destroyExecutorService () {
        if (es != null && !es.isTerminated()) {
            es.shutdownNow();
        }    
    }  
    
